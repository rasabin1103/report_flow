"""Editorial PDF composition: decision brief, evidence, then traceable data appendix."""

import io
from datetime import UTC, datetime
from functools import partial
from html import escape
from numbers import Real
from typing import Any

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, LETTER, landscape
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase import pdfmetrics
from reportlab.platypus import (
    BaseDocTemplate,
    CondPageBreak,
    Frame,
    Image,
    KeepTogether,
    LongTable,
    PageBreak,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)
from reportlab.platypus.tableofcontents import TableOfContents

from app.analytics.metrics import aggregate, grouped
from app.analytics.observations import chart_observation
from app.charts.renderer import render_chart
from app.core.settings import ReportError, Settings
from app.ingestion.loader import Loaded
from app.reporting.cover import CoverPage
from app.reporting.design import TEMPLATES, make_styles
from app.reporting.localization import TEXT, display, metric_label
from app.reporting.pagination import NumberedCanvas
from app.schemas.config import Config, Filter
from app.transformations.engine import apply_filters


class Document(BaseDocTemplate):
    def afterFlowable(self, flowable):
        if isinstance(flowable, Paragraph) and flowable.style.name == "Section":
            self.notify("TOCEntry", (0, flowable.getPlainText(), self.page))


def render(
    loaded: Loaded,
    frame: pd.DataFrame,
    labels: dict[str, str],
    config: Config,
    settings: Settings,
    logo: bytes | None,
) -> bytes:
    out = io.BytesIO()
    language = config.report.language
    es = language == "es"
    tr = TEXT[language]
    template = TEMPLATES[config.report.template]
    size = A4 if config.report.page_size == "A4" else LETTER
    if config.report.orientation == "landscape":
        size = landscape(size)
    width, height = size
    margin = 40
    available = width - margin * 2
    navy = colors.HexColor(config.branding.primary_color)
    accent = colors.HexColor(config.branding.accent_color)
    pale = colors.HexColor("#F0F5F9")
    rule_color = colors.HexColor("#DCE5EC")
    styles = make_styles(config.branding.primary_color, config.branding.accent_color, template)
    now = datetime.now(UTC)
    timestamp = now.strftime("%d/%m/%Y · %H:%M UTC" if es else "%d %b %Y · %H:%M UTC")
    fmt = lambda value: display(value, language)

    def p(text, style="Body"):
        return Paragraph(escape(str(text)), styles[style])

    def filter_text(rule: Filter) -> str:
        value = ""
        if rule.operator not in {"is_null", "is_not_null"}:
            if isinstance(rule.value, list):
                value = ", ".join(fmt(v) for v in rule.value)
            else:
                value = fmt(rule.value)
        return f"{labels.get(rule.column, rule.column)} {tr[rule.operator]} {value}".strip()

    def fit(text: str, max_width: float, font="RF", font_size=7):
        if pdfmetrics.stringWidth(text, font, font_size) <= max_width:
            return text
        while text and pdfmetrics.stringWidth(text + "…", font, font_size) > max_width:
            text = text[:-1]
        return text + "…"

    def page(canvas, doc):
        if doc.page > settings.max_pages:
            raise ReportError("Generated PDF page limit exceeded", 413)
        canvas.setTitle(config.report.title)
        canvas.setAuthor(config.report.author)
        canvas.setFillColor(navy)
        canvas.setFont("RF-Bold", 7)
        canvas.drawString(margin, height - 23, fit(config.branding.company_name, available * 0.30, "RF-Bold"))
        canvas.setFont("RF", 7)
        canvas.drawRightString(width - margin, height - 23, fit(config.report.title, available * 0.65))
        canvas.setStrokeColor(rule_color)
        canvas.setLineWidth(0.5)
        canvas.line(margin, height - 31, width - margin, height - 31)
        canvas.line(margin, 31, width - margin, 31)
        footer = config.branding.footer_text
        if footer == "Generated by ASE ReportFlow":
            footer = tr["footer"]
        canvas.setFillColor(colors.HexColor("#526779"))
        canvas.drawString(margin, 18, fit(footer, available - 65))

    doc = Document(out, pagesize=size, leftMargin=margin, rightMargin=margin, topMargin=46, bottomMargin=43)
    doc.addPageTemplates(
        PageTemplate(
            id="report",
            frames=[
                Frame(
                    margin,
                    43,
                    available,
                    height - 89,
                    leftPadding=0,
                    rightPadding=0,
                    topPadding=0,
                    bottomPadding=0,
                )
            ],
            onPage=page,
        )
    )
    metrics = [(k, aggregate(apply_filters(frame, k.filters), k.operation, k.column)) for k in config.kpis]
    chart_data = [(spec, grouped(frame, spec, config.dataset.missing_policy)) for spec in config.charts]
    observations = [(spec.title, chart_observation(data, spec, language)) for spec, data in chart_data]
    observations = [(title, text) for title, text in observations if text]
    # Prefer one categorical and one temporal observation rather than repeating similar facts.
    selected_observations = observations[:1]
    temporal = next(
        (
            (spec.title, chart_observation(data, spec, language))
            for spec, data in reversed(chart_data)
            if spec.time_granularity and chart_observation(data, spec, language)
        ),
        None,
    )
    if temporal and temporal not in selected_observations:
        selected_observations.append(temporal)
    elif len(observations) > 1:
        selected_observations.append(observations[1])
    selected_observations = selected_observations[:2]

    def section(title):
        return p(title, "Section")

    def insight(text):
        box = Table([[p(text, "Insight")]], colWidths=[available])
        box.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), pale),
                    ("LINEBEFORE", (0, 0), (0, -1), 2, accent),
                    ("LEFTPADDING", (0, 0), (-1, -1), 10),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                    ("TOPPADDING", (0, 0), (-1, -1), 7),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
                ]
            )
        )
        return box

    def kpi_cards():
        result = []
        per_row = 3 if available < 650 else 4
        for start in range(0, len(metrics), per_row):
            chunk = metrics[start : start + per_row]
            gap = 9
            card_width = (available - gap * (len(chunk) - 1)) / len(chunk)
            cells: list[Any] = []
            for metric, value in chunk:
                text = f"{fmt(value)} {metric.unit}".strip()
                font_size = max(
                    11, min(22, (card_width - 24) / max(1, pdfmetrics.stringWidth(text, "RF-Bold", 1)))
                )
                value_style = ParagraphStyle(
                    "Value",
                    fontName="RF-Bold",
                    fontSize=font_size,
                    leading=font_size + 4,
                    textColor=navy,
                    spaceAfter=4,
                )
                content = [p(metric.label, "Small"), Spacer(1, 7), Paragraph(escape(text), value_style)]
                if metric.comparison is not None:
                    delta = None if value is None else float(value) - metric.comparison
                    note = f"{tr['baseline']}: {fmt(metric.comparison)} {metric.unit} · {tr['difference']}: {fmt(delta)} {metric.unit}"
                    content.append(p(note, "Micro"))
                if cells:
                    cells.append("")
                cells.append(content)
            widths = []
            for i in range(len(cells)):
                widths.append(card_width if i % 2 == 0 else gap)
            row = Table([cells], colWidths=widths)
            row.setStyle(
                TableStyle(
                    [
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("LEFTPADDING", (0, 0), (-1, -1), 11),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 11),
                        ("TOPPADDING", (0, 0), (-1, -1), 10),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
                    ]
                )
            )
            for column in range(0, len(cells), 2):
                row.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (column, 0), (column, 0), pale),
                            ("LINEABOVE", (column, 0), (column, 0), 2, accent),
                        ]
                    )
                )
            result.extend([row, Spacer(1, 8)])
        return result

    story = []
    cover = "cover" in config.sections and config.report.include_cover
    if cover and config.report.cover_style == "full":
        story += [
            CoverPage(available, height - 90, config, logo, timestamp, len(frame), len(frame.columns)),
            PageBreak(),
        ]
    elif cover:
        if logo:
            iw, ih = ImageReader(io.BytesIO(logo)).getSize()
            scale = min(130 / iw, 45 / ih)
            story += [
                Image(io.BytesIO(logo), width=iw * scale, height=ih * scale, hAlign="LEFT"),
                Spacer(1, 10),
            ]
        hero = [
            p(config.branding.company_name.upper(), "HeroSub"),
            Spacer(1, 8),
            p(config.report.title, "Hero"),
        ]
        if config.report.subtitle:
            hero.append(p(config.report.subtitle, "HeroSub"))
        panel = Table([[hero]], colWidths=[available])
        panel.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), navy),
                    ("LINEBEFORE", (0, 0), (0, -1), 4, accent),
                    ("LEFTPADDING", (0, 0), (-1, -1), 19),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 19),
                    ("TOPPADDING", (0, 0), (-1, -1), 13),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 17),
                ]
            )
        )
        story += [
            panel,
            Spacer(1, 9),
            p(f"{tr['author']}: {config.report.author}   |   {tr['generated']}: {timestamp}", "Small"),
        ]
        cover_details = [
            value
            for value in [
                config.report.prepared_for,
                config.report.reporting_period,
                config.report.document_reference,
                config.report.confidentiality,
            ]
            if value
        ]
        if cover_details:
            story += [Spacer(1, 5), p(" · ".join(cover_details), "Small")]
    if config.report.include_table_of_contents:
        story += [p(tr["contents"], "ChartTitle")]
        toc = TableOfContents()
        toc.levelStyles = [ParagraphStyle("TOC", fontName="RF", fontSize=9, leading=18, textColor=navy)]
        story += [toc, PageBreak()]
    for name in config.sections:
        if name == "cover" or name == "executive_summary" and not config.report.include_executive_summary:
            continue
        if (
            name == "kpis"
            and not metrics
            or name == "charts"
            and not chart_data
            or name == "tables"
            and not config.tables
        ):
            continue
        if name == "executive_summary":
            story.append(section(tr[name]))
            if len(frame):
                scope = (
                    f"El análisis abarca {fmt(len(frame))} de {fmt(len(loaded.frame))} registros, "
                    f"{len(frame.columns)} columnas seleccionadas y {len(config.filters)} "
                    + ("filtro aplicado." if len(config.filters) == 1 else "filtros aplicados.")
                    if es
                    else f"The analysis covers {fmt(len(frame))} of {fmt(len(loaded.frame))} records, "
                    f"{len(frame.columns)} selected columns and {len(config.filters)} applied "
                    + ("filter." if len(config.filters) == 1 else "filters.")
                )
                story.append(p(scope))
            else:
                story.append(p(tr["no_data"]))
            for title, text in selected_observations:
                story += [p(f"{title} · {text}", "Insight"), Spacer(1, 4)]
            missing = int(frame.isna().sum().sum())
            if missing:
                total = frame.size
                coverage = (total - missing) / total * 100 if total else 0
                note = (
                    f"Cobertura de datos: {fmt(coverage)} % de las celdas seleccionadas tienen valor; {fmt(missing)} celdas sin dato."
                    if es
                    else f"Data coverage: {fmt(coverage)}% of selected cells have a value; {fmt(missing)} cells are missing."
                )
                story.append(p(note, "Small"))
            dates = [frame[c].dropna() for c in frame if pd.api.types.is_datetime64_any_dtype(frame[c])]
            if dates and not dates[0].empty:
                story.append(p(f"{tr['period']}: {fmt(dates[0].min())} – {fmt(dates[0].max())}", "Small"))
        elif name == "kpis":
            story += [section(tr[name]), *kpi_cards()]
        elif name == "charts":
            for index, (spec, data) in enumerate(chart_data, 1):
                limit = min(
                    spec.limit,
                    8 if spec.type in {"pie", "donut"} else 15 if spec.type == "horizontal_bar" else 12,
                )
                shown = data.tail(limit) if spec.time_granularity else data.head(limit)
                omitted = max(0, len(data) - len(shown))
                chart_ratio = (
                    2.6 / 8
                    if config.report.orientation == "landscape"
                    else 2.35 / 8
                    if spec.type == "line" and len(shown) <= 8
                    else template.chart_ratio
                )
                image = render_chart(
                    shown,
                    spec,
                    config.branding.accent_color,
                    labels,
                    language,
                    show_title=False,
                    wide=config.report.orientation == "landscape",
                    aspect_ratio=chart_ratio,
                )
                observation = chart_observation(data, spec, language)
                if (
                    "executive_summary" in config.sections
                    and config.report.include_executive_summary
                    and (spec.title, observation) in selected_observations
                ):
                    observation = None
                calculation = metric_label(spec.aggregation, spec.column, labels, language)
                note = (
                    f"{calculation}. {len(shown)} de {len(data)} categorías; {omitted} omitidas."
                    if es
                    else f"{calculation}. {len(shown)} of {len(data)} categories; {omitted} omitted."
                )
                if spec.type in {"pie", "donut"} and omitted:
                    note += (
                        " Porcentajes sobre las categorías mostradas."
                        if es
                        else " Percentages use displayed categories only."
                    )
                if data["value"].isna().any():
                    note += (
                        " Los agregados nulos no se dibujan." if es else " Null aggregates are not plotted."
                    )
                if any(len(str(v)) > 65 for c in data if c != "value" for v in data[c]):
                    note += " Etiquetas largas abreviadas." if es else " Long labels shortened."
                if omitted and observation:
                    note += (
                        " Observación calculada sobre todos los grupos."
                        if es
                        else " Observation calculated across all groups."
                    )
                parts = [p(f"{index:02}   {spec.title}", "ChartTitle")]
                if config.report.orientation == "landscape":
                    graphic = Image(
                        io.BytesIO(image), width=available * 0.60, height=available * 0.60 * 2.6 / 8
                    )
                    sidebar = ([p(observation, "Insight"), Spacer(1, 9)] if observation else []) + [
                        p(note, "Micro")
                    ]
                    panel = Table([[graphic, sidebar]], colWidths=[available * 0.62, available * 0.38])
                    panel.setStyle(
                        TableStyle(
                            [
                                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                                ("TOPPADDING", (0, 0), (-1, -1), 0),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
                            ]
                        )
                    )
                    parts += [panel, Spacer(1, 12)]
                else:
                    parts.append(Image(io.BytesIO(image), width=available, height=available * chart_ratio))
                    if observation:
                        parts.append(insight(observation))
                    parts += [Spacer(1, 4), p(note, "Micro"), Spacer(1, 14)]
                if index == 1 and config.report.orientation != "landscape":
                    parts.insert(0, section(tr[name]))
                story.append(KeepTogether(parts))
        elif name == "tables":
            if story:
                story.append(CondPageBreak(200))
            appendix_intro = [
                section(tr[name]),
                p(
                    "Detalle de respaldo. Los límites de presentación se indican bajo cada tabla."
                    if es
                    else "Supporting detail. Display limits are disclosed beneath each table.",
                    "Small",
                ),
                Spacer(1, 8),
            ]
            for table_index, table_spec in enumerate(config.tables):
                data = (
                    grouped(frame, table_spec, config.dataset.missing_policy)
                    if table_spec.group_by
                    else frame
                )
                data = data[table_spec.columns]
                table_heading = p(
                    f"{'Tabla' if es else 'Table'} {table_index + 1:02} · {table_spec.title}", "ChartTitle"
                )
                column_labels = {
                    c: (
                        metric_label(table_spec.aggregation, table_spec.column, labels, language)
                        if c == "value" and table_spec.group_by
                        else labels.get(c, c)
                    )
                    for c in table_spec.columns
                }
                rows = [[p(column_labels[c], "TableHeader") for c in table_spec.columns]]
                for _, row in data.head(table_spec.max_rows).iterrows():
                    cells = []
                    for v in row:
                        text = tr["unknown"] if table_spec.group_by and str(v) == "Unknown" else fmt(v)
                        cells.append(
                            p(text, "Numeric" if isinstance(v, Real) and not isinstance(v, bool) else "Cell")
                        )
                    rows.append(cells)
                if table_spec.include_total:
                    total_value = (
                        0
                        if data.empty and table_spec.aggregation in {"count_rows", "count_non_null"}
                        else data["value"].sum(min_count=1)
                    )
                    total_cells = []
                    for position, column in enumerate(table_spec.columns):
                        total_cells.append(
                            p(fmt(total_value), "Numeric")
                            if column == "value"
                            else p("TOTAL" if position == 0 else "", "MethodLabel")
                        )
                    rows.append(total_cells)
                weights = []
                for c in table_spec.columns:
                    sample = data[c].head(40).map(lambda v: len(fmt(v)))
                    length = max(len(column_labels[c]), float(sample.mean()) if len(sample) else 8)
                    weights.append(max(7, min(25, length)) ** 0.7)
                widths = [available * w / sum(weights) for w in weights]
                table = LongTable(rows, colWidths=widths, repeatRows=1, splitInRow=1, hAlign="LEFT")
                table.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, 0), navy),
                            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F3F6F9")]),
                            ("LINEBELOW", (0, 0), (-1, 0), 1, accent),
                            ("VALIGN", (0, 0), (-1, -1), "TOP"),
                            ("LEFTPADDING", (0, 0), (-1, -1), 8),
                            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                            ("TOPPADDING", (0, 0), (-1, -1), template.row_padding),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), template.row_padding),
                        ]
                    )
                )
                if table_spec.include_total:
                    table.setStyle(
                        TableStyle(
                            [
                                ("BACKGROUND", (0, -1), (-1, -1), pale),
                                ("LINEABOVE", (0, -1), (-1, -1), 0.8, accent),
                            ]
                        )
                    )
                count = min(len(data), table_spec.max_rows)
                omitted = max(0, len(data) - count)
                note = (
                    f"Filas mostradas: {fmt(count)}. Filas omitidas: {fmt(omitted)}."
                    if es
                    else f"Rows shown: {fmt(count)}. Rows omitted: {fmt(omitted)}."
                )
                if table_spec.include_total and omitted:
                    note += (
                        " El total incluye todos los grupos, también los omitidos."
                        if es
                        else " The total includes all groups, including those omitted."
                    )
                table_parts = [table_heading, table, Spacer(1, 6), p(note, "Small"), Spacer(1, 12)]
                if table_index == 0:
                    table_parts = appendix_intro + table_parts
                if count <= 20:
                    story.append(KeepTogether(table_parts))
                else:
                    story += [CondPageBreak(95), *table_parts]
        elif name == "methodology":
            details = [
                (tr["source"], loaded.filename),
                (tr["worksheet"], loaded.selected_sheet or "—"),
                (tr["loaded"], fmt(len(loaded.frame))),
                (tr["analyzed"], fmt(len(frame))),
                (tr["selected"], ", ".join(labels[str(c)] for c in frame)),
                (tr["filters"], "; ".join(filter_text(rule) for rule in config.filters) or tr["none"]),
                (
                    tr["missing_policy"],
                    ("Incluir como «Sin dato»" if es else "Include as Unknown")
                    if config.dataset.missing_policy == "unknown"
                    else ("Excluir" if es else "Exclude"),
                ),
            ]
            for key, value in [
                ("Preparado para" if es else "Prepared for", config.report.prepared_for),
                ("Periodo del informe" if es else "Reporting period", config.report.reporting_period),
                ("Referencia" if es else "Reference", config.report.document_reference),
                ("Confidencialidad" if es else "Confidentiality", config.report.confidentiality),
            ]:
                if value:
                    details.append((key, value))
            for metric, _ in metrics:
                calculation = metric_label(metric.operation, metric.column, labels, language)
                if metric.filters:
                    calculation += "; " + "; ".join(filter_text(rule) for rule in metric.filters)
                details.append((metric.label, calculation))
            details.append((tr["generated"], timestamp))
            method_rows = []
            for position in range(0, len(details), 2):
                pair = details[position : position + 2]
                cells = []
                for key, value in pair:
                    cells.extend([p(key, "MethodLabel"), p(value, "Small")])
                if len(cells) == 2:
                    cells.extend(["", ""])
                method_rows.append(cells)
            method_table = Table(
                method_rows,
                colWidths=[available * 0.17, available * 0.33, available * 0.17, available * 0.33],
                hAlign="LEFT",
                splitInRow=1,
            )
            method_table.setStyle(
                TableStyle(
                    [
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("LINEBELOW", (0, 0), (-1, -1), 0.3, rule_color),
                        ("LEFTPADDING", (0, 0), (-1, -1), 0),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 9),
                        ("TOPPADDING", (0, 0), (-1, -1), 1),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
                    ]
                )
            )
            note = (
                "Fechas normalizadas a UTC; semanas de lunes a domingo. Los valores nulos no se convierten en cero. "
                "Los filtros se combinan con Y. Las observaciones describen los datos; no atribuyen causas ni predicen resultados."
                if es
                else "Dates normalized to UTC; weeks run Monday to Sunday. Null values are not replaced with zero. "
                "Filters combine with AND. Observations describe the data; they do not establish causes or predict outcomes."
            )
            method_parts = [section(tr[name]), method_table, Spacer(1, 7), p(note, "Micro")]
            if loaded.warnings:
                warning = (
                    "Excel: solo se leen resultados de fórmulas almacenados. Sin valor almacenado, la celda se considera nula."
                    if es
                    else "Excel: only cached formula results are read. Missing cached results are treated as null."
                )
                method_parts += [Spacer(1, 4), p(warning, "Micro")]
            story.append(KeepTogether(method_parts))
    if not story:
        story = [
            section(config.report.title),
            p("No hay secciones seleccionadas." if es else "No sections selected."),
        ]
    doc.multiBuild(story, canvasmaker=partial(NumberedCanvas, page_label=tr["page"], of_label=tr["of"]))
    return out.getvalue()
