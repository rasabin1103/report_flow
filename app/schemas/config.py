from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

Operation = Literal["count_rows", "count_non_null", "sum", "average", "minimum", "maximum", "distinct_count"]
Section = Literal["cover", "executive_summary", "kpis", "charts", "tables", "methodology"]


def default_sections() -> list[Section]:
    return ["cover", "executive_summary", "kpis", "charts", "tables", "methodology"]


Operator = Literal[
    "equals",
    "not_equals",
    "greater_than",
    "greater_or_equal",
    "less_than",
    "less_or_equal",
    "in",
    "not_in",
    "contains",
    "is_null",
    "is_not_null",
    "between",
]


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", str_max_length=2000, allow_inf_nan=False)


class Filter(Strict):
    column: str
    operator: Operator
    value: Any = None


class Column(Strict):
    source: str
    label: str | None = None
    type: Literal["string", "number", "integer", "date", "boolean"] | None = None
    include: bool = True


class Dataset(Strict):
    sheet_name: str | None = None
    encoding: Literal["utf-8", "utf-8-sig", "latin-1", "cp1252"] = "utf-8-sig"
    delimiter: str | None = Field(default=None, min_length=1, max_length=1)
    columns: list[Column] = Field(default_factory=list, max_length=80)
    missing_policy: Literal["exclude", "unknown"] = "unknown"


class Metric(Strict):
    id: str
    label: str = Field(max_length=160)
    operation: Operation
    column: str | None = None
    filters: list[Filter] = Field(default_factory=list, max_length=30)
    unit: str = Field(default="", max_length=32)
    comparison: float | None = None


class Group(Strict):
    id: str
    title: str
    group_by: str | list[str]
    aggregation: Operation = "count_rows"
    column: str | None = None
    time_granularity: Literal["day", "week", "month", "quarter", "year"] | None = None
    sort: Literal["ascending", "descending"] = "descending"
    limit: int = Field(default=15, ge=1, le=40)


class Chart(Group):
    type: Literal["bar", "horizontal_bar", "line", "pie", "donut"]
    unit: str = Field(default="", max_length=32)


class Table(Strict):
    id: str
    title: str
    columns: list[str] = Field(min_length=1, max_length=12)
    max_rows: int = Field(default=100, ge=1, le=2000)
    include_total: bool = False
    group_by: str | list[str] | None = None
    aggregation: Operation = "count_rows"
    column: str | None = None
    sort: Literal["ascending", "descending"] = "descending"


class Report(Strict):
    title: str = Field(default="ASE ReportFlow", min_length=1, max_length=200)
    subtitle: str = Field(default="", max_length=300)
    author: str = Field(default="ASE ReportFlow", max_length=160)
    prepared_for: str = Field(default="", max_length=160)
    reporting_period: str = Field(default="", max_length=80)
    document_reference: str = Field(default="", max_length=80)
    confidentiality: str = Field(default="", max_length=100)
    language: Literal["en", "es"] = "en"
    page_size: Literal["A4", "LETTER"] = "A4"
    orientation: Literal["portrait", "landscape"] = "portrait"
    template: Literal["executive", "detailed"] = "executive"
    include_cover: bool = True
    cover_style: Literal["compact", "full"] = "compact"
    include_table_of_contents: bool = False
    include_executive_summary: bool = True

    @field_validator("title")
    @classmethod
    def nonblank_title(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Report title must contain visible text")
        return value.strip()


class Branding(Strict):
    company_name: str = Field(default="ASE ReportFlow", max_length=160)
    primary_color: str = Field(default="#0B1929", pattern=r"^#[0-9a-fA-F]{6}$")
    accent_color: str = Field(default="#1A8FE3", pattern=r"^#[0-9a-fA-F]{6}$")
    footer_text: str = Field(default="Generated by ASE ReportFlow", max_length=120)
    logo_base64: str | None = Field(default=None, max_length=700000)


class Config(Strict):
    schema_version: Literal["1.0"] = "1.0"
    report: Report = Field(default_factory=Report)
    dataset: Dataset = Field(default_factory=Dataset)
    filters: list[Filter] = Field(default_factory=list, max_length=30)
    kpis: list[Metric] = Field(default_factory=list, max_length=24)
    charts: list[Chart] = Field(default_factory=list, max_length=12)
    tables: list[Table] = Field(default_factory=list, max_length=12)
    sections: list[Section] = Field(
        default_factory=default_sections,
        max_length=6,
    )
    branding: Branding = Field(default_factory=Branding)

    @model_validator(mode="after")
    def consistency(self):
        for values in (
            [c.source for c in self.dataset.columns],
            self.sections,
            [x.id for x in self.kpis] + [x.id for x in self.charts] + [x.id for x in self.tables],
        ):
            if len(set(values)) != len(values):
                raise ValueError("Duplicate column, section or component identifier")
        return self
