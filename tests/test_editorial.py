"""Regression checks for evidence, localization, and the editorial document contract."""

import io
import json
from pathlib import Path

import pandas as pd
import pytest
from pypdf import PdfReader

from app.analytics.observations import chart_observation
from app.reporting.localization import display
from app.schemas.config import Chart
from app.services.reports import execute


def spec(**kwargs):
    return Chart(id="evidence", title="Distribution", type="bar", group_by="category", **kwargs)


def text_of(pdf):
    return "\n".join(page.extract_text() for page in PdfReader(io.BytesIO(pdf)).pages)


def test_shares_use_full_grouping_before_category_limit():
    data = pd.DataFrame({"category": ["A", "B", "C"], "value": [4, 3, 3]})
    observation = chart_observation(data, spec(limit=1))
    assert "40%" in observation
    assert "100%" not in observation


@pytest.mark.parametrize(
    "operation,values", [("average", [4, 2]), ("distinct_count", [4, 2]), ("sum", [4, -2])]
)
def test_nonadditive_or_negative_metrics_have_no_share(operation, values):
    observation = chart_observation(
        pd.DataFrame({"category": ["A", "B"], "value": values}), spec(aggregation=operation)
    )
    assert "%" not in observation


def test_ties_and_all_missing_values():
    data = pd.DataFrame({"category": ["A", "B", "C"], "value": [5, 5, 2]})
    observation = chart_observation(data, spec())
    assert "A, B" in observation and "41.67%" in observation
    data["value"] = [2, 2, 2]
    assert "same value" in chart_observation(data, spec())
    data["value"] = [None, None, None]
    assert chart_observation(data, spec()) is None


def test_partial_null_metrics_disclose_scope():
    data = pd.DataFrame({"category": ["A", "B", "C"], "value": [8, None, 2]})
    observation = chart_observation(data, spec())
    assert "groups with available values" in observation and "%" not in observation


def test_temporal_comparison_orders_dates_and_discloses_partial_intervals():
    chart = Chart(id="date", title="Trend", type="line", group_by="date", time_granularity="month")
    data = pd.DataFrame({"date": pd.to_datetime(["2026-03-01", "2026-01-01"]), "value": [12, 10]})
    observation = chart_observation(data, chart)
    assert "20%" in observation and "may be incomplete" in observation
    assert "2026-01-01" in observation and "2026-03-01" in observation
    data["value"] = [12, 0]
    assert chart_observation(data, chart) is None


@pytest.mark.parametrize(
    "value,en,es",
    [
        (1449630, "1,449,630", "1.449.630"),
        (2684.5, "2,684.5", "2.684,5"),
        (True, "Yes", "Sí"),
        (None, "—", "—"),
    ],
)
def test_locale_independent_formatting(value, en, es):
    assert display(value, "en") == en
    assert display(value, "es") == es


def test_spanish_pdf_has_correct_unicode_and_localized_prose():
    data = "categoría,importe,fecha\nÁrbol,100,2026-01-01\nCórdoba,200,2026-02-01\n".encode()
    config = {
        "report": {"language": "es", "title": "Revisión de operación"},
        "kpis": [
            {
                "id": "total",
                "label": "Importe total",
                "operation": "sum",
                "column": "importe",
                "unit": "EUR",
                "comparison": 250,
            }
        ],
        "filters": [{"column": "importe", "operator": "greater_than", "value": 0}],
        "charts": [
            {
                "id": "chart",
                "title": "Importe por categoría",
                "type": "bar",
                "group_by": "categoría",
                "aggregation": "sum",
                "column": "importe",
                "unit": "EUR",
            }
        ],
        "tables": [{"id": "table", "title": "Detalle", "columns": ["categoría", "importe"]}],
    }
    result = execute("generate", data, "operación.csv", json.dumps(config))
    text = text_of(result)
    for required in [
        "Síntesis ejecutiva",
        "Revisión de operación",
        "Importe total",
        "Referencia",
        "Diferencia",
        "Filas mostradas",
        "Alcance y metodología",
        "Importe por categoría",
        "es mayor que",
    ]:
        assert required in text
    for forbidden in ["Ã", "Â", "â€", "Rows shown", "Source:", "Baseline:", "Unknown", "Generated by"]:
        assert forbidden not in text
    first = PdfReader(io.BytesIO(result)).pages[0].extract_text()
    assert "Importe total" in first and "Importe por categoría" in first


def test_full_cover_and_contents_remain_available():
    config = {
        "report": {"title": "Long form", "cover_style": "full", "include_table_of_contents": True},
        "kpis": [{"id": "rows", "label": "Rows", "operation": "count_rows"}],
    }
    result = execute("generate", b"a\nx\ny\n", "data.csv", json.dumps(config))
    reader = PdfReader(io.BytesIO(result))
    assert len(reader.pages) >= 3
    assert "Contents" in reader.pages[1].extract_text()
    assert "Contents" not in reader.pages[1].extract_text().split("Contents", 1)[1]


def test_editorial_examples_are_compact_and_disclose_omissions():
    for stem, max_pages in [("qa", 3), ("sales", 3), ("projects", 2)]:
        reader = PdfReader(Path(f"examples/{stem}_report.pdf"))
        assert len(reader.pages) <= max_pages
        text = "\n".join(page.extract_text() for page in reader.pages)
        assert ("Filas omitidas:" if stem == "qa" else "Rows omitted:") in text
        first = reader.pages[0].extract_text()
        assert ("Indicadores principales" if stem == "qa" else "Performance at a glance") in first


def test_landscape_opening_includes_chart_evidence():
    config = json.loads(Path("examples/projects_config.json").read_text(encoding="utf-8"))
    config["report"]["orientation"] = "landscape"
    result = execute(
        "generate", Path("examples/projects.csv").read_bytes(), "projects.csv", json.dumps(config)
    )
    first = PdfReader(io.BytesIO(result)).pages[0].extract_text()
    assert "01 Projects by status" in " ".join(first.split())
